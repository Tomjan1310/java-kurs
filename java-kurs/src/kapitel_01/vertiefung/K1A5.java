package kapitel_01.vertiefung;
public class K1A5 {
    public static void main(String[] args) {
        System.out.println(1 / 2); /* 0  int / int = int/Ganzkommazahl*/
        System.out.println(1.0 / 2); /* 0.5  double / int = double/Fließkommazahl*/
        System.out.println(1 / 2.0); /* 0.5  int / double = double*/
        System.out.println(5 / 2); /* 2  int / int = int*/
        System.out.println(5.0 / 2); /* 2.5 double / int = double*/
    }
}
